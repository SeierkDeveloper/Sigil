// Writes web/src/vault/selfWalletCode.ts from the Foundry build of
// contracts/src/SigilSelfWallet.sol, so the vault can deploy the self's wallet
// from the owner's own browser wallet. Run after changing the contract:
//   (cd contracts && forge build) && node web/scripts/self-wallet-code.mjs
// A unit test checks the file against the build, and the end-to-end test
// deploys it on a local chain and compares the code on chain.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const art = JSON.parse(readFileSync(path.join(root, "contracts/out/SigilSelfWallet.sol/SigilSelfWallet.json"), "utf8"));
const code = art.bytecode.object;
if (!/^0x[0-9a-f]+$/.test(code)) throw new Error("No bytecode in the build. Run forge build in contracts/ first.");
const out = `// Generated by web/scripts/self-wallet-code.mjs from contracts/src/SigilSelfWallet.sol
// (solc 0.8.28, optimizer 10,000 runs, as in contracts/foundry.toml). Do not edit by hand.

/** The creation code of SigilSelfWallet, without constructor arguments. */
export const SELF_WALLET_BYTECODE = "${code}" as const;
`;
writeFileSync(path.join(root, "web/src/vault/selfWalletCode.ts"), out);
console.log(`selfWalletCode.ts: ${(code.length - 2) / 2} bytes of creation code`);
